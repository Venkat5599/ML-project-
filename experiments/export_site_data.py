"""Export committed results into the website console's static data module.

Writes website/lib/dash/real.ts from results/metrics/*.json and the per-step
label counts of the dataset, so the console's model and time-step pages never
carry hand-typed numbers. Re-run after any experiment that changes metrics:

    python -m experiments.export_site_data
"""
from __future__ import annotations

import json
from pathlib import Path

from chainsleuth.config import METRICS_DIR, PROJECT_ROOT

OUT = PROJECT_ROOT / "website" / "lib" / "dash" / "real.ts"

# (console key, metrics file stem, display name, short label, family)
MODELS = [
    ("logistic_regression", "final_logistic_regression", "Logistic regression", "LR", "tabular"),
    ("decision_tree", "final_decision_tree", "Decision tree", "DT", "tabular"),
    ("random_forest", "final_random_forest", "Random forest", "RF", "tabular"),
    ("xgboost", "final_xgboost", "XGBoost (tuned)", "XGB", "tabular"),
    ("svm", "final_svm", "SVM (RBF)", "SVM", "tabular"),
    ("isolation_forest", "final_isolation_forest", "Isolation forest", "IF", "anomaly"),
    ("autoencoder", "final_autoencoder", "Autoencoder", "AE", "anomaly"),
    ("graphsage", "final_graphsage", "GraphSAGE", "GNN", "graph"),
    ("xgb_graph_features", "final_xgb_graph_features", "XGBoost + graph features", "XGB+GF", "experiment"),
    ("xgb_gnn_blend", "final_xgb_gnn_blend", "XGBoost + GNN blend", "Blend", "ensemble"),
    ("ensemble_weighted", "final_ensemble_weighted", "Weighted ensemble", "Ens-W", "ensemble"),
    ("ensemble_stacked", "final_ensemble_stacked", "Stacked ensemble", "Ens-S", "ensemble"),
    ("ensemble_calibrated", "final_ensemble_calibrated", "Calibrated ensemble", "Ens-C", "ensemble"),
    ("xgboost_random_split", "experiment_random_split_xgboost", "XGBoost, random split", "XGB-rand", "experiment"),
    ("xgboost_top30_features", "experiment_top30_features_xgboost", "XGBoost, top-30 features", "XGB-30", "experiment"),
]

COMPONENT_NAMES = {"xgb": "XGBoost", "rf": "Random forest", "ae": "Autoencoder",
                   "gnn": "GraphSAGE", "iso": "Isolation forest"}


def _load(stem: str, metrics_dir: Path) -> dict:
    path = metrics_dir / f"{stem}.json"
    if not path.exists():
        raise FileNotFoundError(f"{path} missing - run the experiment that writes it first")
    return json.loads(path.read_text())


def model_rows(metrics_dir: Path = METRICS_DIR) -> list[dict]:
    rows = []
    for key, stem, name, short, family in MODELS:
        t = _load(stem, metrics_dir)["test"]
        rows.append({
            "key": key, "name": name, "short": short, "family": family,
            "p": t["precision"], "r": t["recall"], "f1": t["f1"],
            "ap": t["avg_precision"], "auc": t["roc_auc"], "p100": t["precision@100"],
            "nEval": t["n_eval"], "nPos": t["n_positive"],
        })
    return rows


def weight_rows(metrics_dir: Path = METRICS_DIR) -> list[dict] | None:
    """Tuned ensemble weights, largest first; None if hybrid.py predates saving them."""
    w = _load("final_ensemble_weighted", metrics_dir).get("weights")
    if not w:
        return None
    return [{"name": COMPONENT_NAMES.get(k, k), "weight": round(v, 4)}
            for k, v in sorted(w.items(), key=lambda kv: -kv[1])]


def per_step(df) -> list[dict]:
    g = df.groupby("time_step")["label"]
    return [{"step": int(s), "total": int(len(lab)), "labelled": int((lab >= 0).sum()),
             "illicit": int((lab == 1).sum())} for s, lab in g]


def eda_block(df, n_edges: int) -> dict:
    return {
        "n_total": int(len(df)),
        "n_illicit": int((df["label"] == 1).sum()),
        "n_licit": int((df["label"] == 0).sum()),
        "n_unknown": int((df["label"] < 0).sum()),
        "n_time_steps": int(df["time_step"].nunique()),
        "n_edges": int(n_edges),
    }


def render(models: list[dict], steps: list[dict], eda: dict, weights: list[dict] | None) -> str:
    lines = [
        "// Generated by `python -m experiments.export_site_data` from results/metrics",
        "// and the dataset's per-step label counts. Do not hand-edit.",
        f"export const MODELS = {json.dumps(models, indent=1)};",
        f"export const PER_STEP = {json.dumps(steps)};",
        f"export const EDA = {json.dumps(eda)};",
        "// tuned on the validation window (steps 30-34) by experiments/hybrid.py",
        f"export const WEIGHTS: {{ name: string; weight: number }}[] | null = {json.dumps(weights)};",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    from chainsleuth.data import load_dataset, load_raw

    df = load_dataset()
    _, _, edges = load_raw()
    text = render(model_rows(), per_step(df), eda_block(df, len(edges)), weight_rows())
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
